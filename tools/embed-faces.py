"""Embeds the boss face images into js/bossfaces.js as data URIs.

Browsers refuse to give WebGL images loaded from file:// pages, so the 3D view
needs the faces inline to work when index.html is double-clicked.
Re-run after changing images in assets/bosses/:  python tools/embed-faces.py
"""
import base64, json, os, re

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
bosses = open(os.path.join(root, 'js', 'bosses.js'), encoding='utf-8').read()
faces = {}
for path in re.findall(r"image:\s*'([^']+)'", bosses):
    full = os.path.join(root, path)
    if not os.path.exists(full):
        continue
    mime = 'image/png' if path.lower().endswith('.png') else 'image/jpeg'
    faces[path] = 'data:%s;base64,%s' % (mime, base64.b64encode(open(full, 'rb').read()).decode())
with open(os.path.join(root, 'js', 'bossfaces.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/embed-faces.py. Boss face images inlined so the 3D view works from file://.\n')
    f.write('window.PTD = window.PTD || {};\nPTD.BOSS_FACES = ' + json.dumps(faces) + ';\n')
print(len(faces), 'faces embedded')
