"""Embeds assets/models/*.glb into js/models.js as base64 so the 3D view can load them
even from a double-clicked index.html (browsers block fetch() on file://).
Re-run after rebuilding models:  python tools/embed-models.py
"""
import base64, glob, json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
models = {}
for path in sorted(glob.glob(os.path.join(root, 'assets', 'models', '*.glb'))):
    models[os.path.splitext(os.path.basename(path))[0]] = base64.b64encode(open(path, 'rb').read()).decode()
with open(os.path.join(root, 'js', 'models.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/embed-models.py from assets/models/*.glb (built with tools/blender/looters.py).\n')
    f.write('window.PTD = window.PTD || {};\nPTD.MODEL_DATA = ' + json.dumps(models) + ';\n')
print(len(models), 'models embedded')
